// Falls back to English if a key is missing in a language, so the app never
// shows a blank label while translations are being filled in.
//
// Supports {0}, {1}... placeholders so sentences with numbers in them can be
// translated as whole sentences rather than glued together from fragments.
// Word order differs between these languages, so building sentences by
// concatenation would produce nonsense in at least one of them.
export function translate(lang, key, params) {
  let out = strings[lang]?.[key] ?? strings.en[key] ?? key;
  if (params && params.length) {
    params.forEach((v, i) => {
      out = out.split("{" + i + "}").join(String(v));
    });
  }
  return out;
}

// The engine returns {key, vals} instead of finished English sentences.
// This turns one of those into text in the current language.
export function translateDetail(lang, detail) {
  if (!detail) return "";
  if (typeof detail === "string") return detail;
  return translate(lang, detail.key, detail.vals);
}

